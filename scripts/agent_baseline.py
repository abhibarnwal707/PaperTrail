"""Compare the LLM investigator with the deterministic baseline on the same 30 cases (offline: uses the cached summaries, no API key).

    python scripts/agent_baseline.py

Reads data/demo/cached_cases.json (from scripts/agent_eval.py) and the tools over data/demo; writes reports/agent_vs_baseline.md + .json.
Ground truth (alerts.typologies_truth) is used only for scoring. Cost: token counts are measured; dollars are NOT estimated unless you pass
--usd-per-mtok (the runs used free-tier models, so the actual spend was 0).
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from papertrail.agent.baseline import template_summary
from papertrail.agent.schemas import CaseSummary
from papertrail.agent.tools import Toolbox
from papertrail.agent.verify import check

DEMO, REPORTS = ROOT / "data" / "demo", ROOT / "reports"


def pct(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "n/a"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--usd-per-mtok", type=float, default=None, help="optional price per million tokens to turn tokens into a cost estimate")
    args = ap.parse_args()
    tb = Toolbox(DEMO)
    cache = json.loads((DEMO / "cached_cases.json").read_text())
    truth = {r["account"]: r for r in tb.alerts.select("account", "typologies_truth", "n_laundering").to_dicts()}
    eval_accounts = [c["account"] for c in json.loads((REPORTS / "agent_eval.json").read_text())["cases"]]

    rows = []
    for acct in eval_accounts:
        outs = tb.gather(acct)
        base = template_summary(acct, outs)
        assert check(CaseSummary.model_validate(base), outs, acct) == []        # the baseline must pass the same guardrail
        agent = cache[acct]
        true = [x for x in (truth[acct]["typologies_truth"] or "").split("; ") if x]
        a, b = agent["summary"], base
        rows.append({"account": acct, "laundering": bool(truth[acct]["n_laundering"]), "truth": true,
                     "agent_typology": a["suspected_typology"], "base_typology": b["suspected_typology"],
                     "agent_action": a["recommended_action"], "base_action": b["recommended_action"],
                     "agent_tokens": agent.get("tokens"), "agent_latency_s": agent.get("total_latency_s"), "agent_retried": agent["retried"]})

    pos, neg = [r for r in rows if r["laundering"]], [r for r in rows if not r["laundering"]]

    def acc(rs, who):
        return sum(r[f"{who}_typology"] in r["truth"] for r in rs)

    def named(rs, who):
        return sum(r[f"{who}_typology"] != "UNCLEAR" for r in rs)

    s = {
        "cases": len(rows), "laundering_cases": len(pos), "clean_cases": len(neg),
        "typology_correct": {"agent": acc(pos, "agent"), "baseline": acc(pos, "base")},
        "typology_named": {"agent": named(pos, "agent"), "baseline": named(pos, "base")},
        "sar_on_laundering": {"agent": sum(r["agent_action"] == "escalate_SAR" for r in pos), "baseline": sum(r["base_action"] == "escalate_SAR" for r in pos)},
        "sar_on_clean": {"agent": sum(r["agent_action"] == "escalate_SAR" for r in neg), "baseline": sum(r["base_action"] == "escalate_SAR" for r in neg)},
        "action_agreement": sum(r["agent_action"] == r["base_action"] for r in rows),
        "agent_right_baseline_wrong": [r["account"] for r in pos if r["agent_typology"] in r["truth"] and r["base_typology"] not in r["truth"]],
        "baseline_right_agent_wrong": [r["account"] for r in pos if r["base_typology"] in r["truth"] and r["agent_typology"] not in r["truth"]],
        "agent_tokens_total": sum(r["agent_tokens"] or 0 for r in rows),
        "agent_tokens_mean": statistics.mean(r["agent_tokens"] for r in rows if r["agent_tokens"]),
        "agent_latency_mean_s": statistics.mean(r["agent_latency_s"] for r in rows if r["agent_latency_s"]),
        "agent_retries": sum(r["agent_retried"] for r in rows),
    }
    if args.usd_per_mtok is not None:
        s["agent_cost_usd_estimate"] = s["agent_tokens_total"] * args.usd_per_mtok / 1e6
    REPORTS.joinpath("agent_vs_baseline.json").write_text(json.dumps({"summary": s, "cases": rows}, indent=1))

    n, m = len(pos), len(neg)
    diff = s["typology_correct"]["agent"] - s["typology_correct"]["baseline"]
    intro = (f"Same {len(rows)} cases ({n} laundering, {m} clean-but-flagged), same tool outputs. Baseline = `agent/baseline.py`: rule-based typology "
             "(thresholds fixed a priori, can only name CYCLE / FAN-IN / FAN-OUT / GATHER-SCATTER), the prompt's escalation policy in code, and a templated "
             "summary from the alert and SHAP outputs (passes the guardrail by construction). Generated by `scripts/agent_baseline.py`, offline.")
    reading = (f"On typology the agent is ahead by {diff} of {n} cases, which is within what 30 cases can distinguish from noise; "
               f"it takes the same action as the baseline on {s['action_agreement']} of {len(rows)} cases; false escalations are "
               f"{s['sar_on_clean']['agent']} vs {s['sar_on_clean']['baseline']}. For that it costs {s['agent_tokens_mean']:,.0f} tokens and "
               f"{s['agent_latency_mean_s']:.1f} s per case against none. Where the agent can add value is the plain-English narrative, which no metric here "
               "scores, and typologies the rules cannot name (SCATTER-GATHER, STACK, BIPARTITE, RANDOM); the data shows no measurable gain on them. "
               "The typology truth is synthetic and often lists several patterns per account (a prediction counts as right if it is any of them).")
    md = ["# LLM investigator vs deterministic baseline", "", intro, "",
          "| Measure | LLM agent | Baseline |", "|---|---|---|",
          f"| Typology correct (laundering accounts) | {pct(s['typology_correct']['agent'], n)} | {pct(s['typology_correct']['baseline'], n)} |",
          f"| Named a pattern instead of UNCLEAR | {pct(s['typology_named']['agent'], n)} | {pct(s['typology_named']['baseline'], n)} |",
          f"| Escalated to SAR, laundering accounts | {pct(s['sar_on_laundering']['agent'], n)} | {pct(s['sar_on_laundering']['baseline'], n)} |",
          f"| Escalated to SAR, clean accounts (false escalations) | {pct(s['sar_on_clean']['agent'], m)} | {pct(s['sar_on_clean']['baseline'], m)} |",
          f"| Cost per case | {s['agent_tokens_mean']:,.0f} tokens, {s['agent_latency_mean_s']:.1f} s mean | 0 tokens, instant |",
          f"| Drafts the guardrail rejected | {s['agent_retries']} of {len(rows)} | none possible (template) |", "",
          (f"Same action on {s['action_agreement']} of {len(rows)} cases. Agent right and baseline wrong on typology: "
           f"{len(s['agent_right_baseline_wrong'])} accounts; baseline right and agent wrong: {len(s['baseline_right_agent_wrong'])}."), "",
          "## Reading it", "", reading, ""]
    if args.usd_per_mtok is not None:
        md.insert(-1, f"Estimated agent cost at {args.usd_per_mtok} USD per million tokens (your price, not measured): "
                      f"{s['agent_cost_usd_estimate']:.4f} USD for {len(rows)} cases.")
    REPORTS.joinpath("agent_vs_baseline.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
